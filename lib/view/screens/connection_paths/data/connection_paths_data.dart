  static ConnectionPath? byId(String id) {
    for (final p in all) {
      if (p.id == id) return p;
    }
    return null;
  }

  static List<ConnectionPath> forDuration(int? days) =>
      days == null ? all : all.where((p) => p.durationDays == days).toList();

  static List<ConnectionPath> get featured =>
      featuredIds.map(byId).whereType<ConnectionPath>().toList();

  static const _reflections = [
    'What stood out to you most in today\'s verse?',
    'How can you live out today\'s truth in one practical way?',
    'What is one thing you want to talk to God about today?',
    'Where do you most need God\'s help right now?',
    'How has God been faithful to you recently?',
    'What would change today if you fully believed this verse?',
  ];

  static List<PathDay> _build(String pathTitle, List<_S> specs) {
    return List<PathDay>.generate(specs.length, (i) {
      final s = specs[i];
      return PathDay(
        title: s.title,
        subtitle: s.subtitle,
        verseRef: s.ref,
        devotion: s.devotion,
        reflection: s.reflection ?? _reflections[i % _reflections.length],
        prayer:
            'Lord, thank You for speaking to me through "${s.title}". Help me live this truth today and walk closely with You on my $pathTitle path. Guide my heart and keep me near You. Amen.',
      );
    });
  }
}

class _S {
  const _S(this.title, this.subtitle, this.ref, this.devotion,
      [this.reflection]);

  final String title;
  final String subtitle;
  final String ref;
  final String devotion;
  final String? reflection;
}
